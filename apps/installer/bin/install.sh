#!/usr/bin/env bash
#
# install.sh — AgentWorks OS one-command bootstrap
# Usage:
#   curl -fsSL https://get.agentworks.os/install.sh | bash
#   curl -fsSL https://get.agentworks.os/install.sh | bash -s -- --unattended
#
# Detects when it is running inside a local repo checkout and uses local files
# rather than downloading from GitHub.
set -euo pipefail

INSTALLER_VERSION="0.3.0-alpha.2"  # BUMP ON RELEASE
REPO="SGridworks/agentworks-os"
RAW_BASE="https://raw.githubusercontent.com/${REPO}/main"

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
# If AGENTWORKS_DIR is unset, default to ~/.agentworks.  When run from a
# repo checkout the installer uses the repo root as the working directory so
# docker compose finds the local docker-compose.yml.
AGENTWORKS_DIR="${AGENTWORKS_DIR:-$HOME/.agentworks}"
DATA_DIR="${AGENTWORKS_DIR}/data"
CONFIG_DIR="${AGENTWORKS_DIR}/config"
LOG_DIR="${AGENTWORKS_DIR}/logs"
RULE_PACKS_DIR="${AGENTWORKS_DIR}/rule-packs"

# Where this script lives (used only when installed as a Docker image)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ---------------------------------------------------------------------------
# Colours
# ---------------------------------------------------------------------------
if [[ -t 1 ]]; then
  RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[0;33m'
  BLUE='\033[0;34m'; NC='\033[0m'
else
  RED=''; GREEN=''; YELLOW=''; BLUE=''; NC=''
fi

log_info()  { echo -e "${GREEN}[INFO]${NC} $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC} $*" >&2; }
log_error() { echo -e "${RED}[ERROR]${NC} $*" >&2; }
log_step()  { echo -e "${BLUE}[STEP]${NC} $*"; }

# ---------------------------------------------------------------------------
# Detect: local checkout vs. curl-based install
# ---------------------------------------------------------------------------
is_local_checkout() {
  [[ -f "$(pwd)/docker-compose.yml" ]] && \
    grep -q "agentos-d" "$(pwd)/docker-compose.yml" 2>/dev/null
}

# ---------------------------------------------------------------------------
# 1. Docker check
# ---------------------------------------------------------------------------
check_docker() {
  log_step "Checking Docker..."

  if ! command -v docker &>/dev/null; then
    log_error "Docker is not installed."
    log_error "Visit https://docs.docker.com/get-docker/ to install Docker."
    exit 1
  fi

  if ! docker info &>/dev/null 2>&1; then
    log_error "Docker daemon is not running."
    log_error "Please start Docker Desktop (or dockerd on Linux) and try again."
    exit 1
  fi

  local version
  version=$(docker version --format '{{.Server.Version}}' 2>/dev/null || echo "unknown")
  log_info "Docker ${version} — OK"
}

# ---------------------------------------------------------------------------
# 2. Create .env with generated AGENTWORKS_SESSION_SECRET
# ---------------------------------------------------------------------------
create_env() {
  log_step "Creating ${AGENTWORKS_DIR}/.env ..."

  # Detect whether we need to generate or can reuse an existing secret
  local env_file="${AGENTWORKS_DIR}/.env"

  # Generate secrets
  local session_secret admin_password db_password

  if command -v openssl &>/dev/null; then
    session_secret=$(openssl rand -hex 32)
    admin_password=$(openssl rand -base64 32 | tr -d '=\n/' | head -c 32)
    db_password=$(openssl rand -base64 32 | tr -d '=\n' | head -c 32)
  else
    # Fallback: use /dev/urandom
    session_secret=$(head -c 32 /dev/urandom | xxd -p)
    admin_password=$(head -c 32 /dev/urandom | xxd -p | head -c 32)
    db_password=$(head -c 32 /dev/urandom | xxd -p | head -c 32)
  fi

  # Resolve the installed version: prefer the release tag fetched at runtime,
  # fall back to the compiled-in INSTALLER_VERSION constant.
  local resolved_version
  resolved_version=$(curl -sL "https://api.github.com/repos/${REPO}/releases?per_page=1" 2>/dev/null \
    | sed -nE 's/.*"tag_name"[[:space:]]*:[[:space:]]*"v?([^"]+)".*/\1/p' | head -1 || true)
  [[ -z "$resolved_version" ]] && resolved_version="${INSTALLER_VERSION}"

  cat > "${env_file}" <<EOF
# Auto-generated by AgentWorks OS installer on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# DO NOT COMMIT THIS FILE
AGENTWORKS_VERSION=${resolved_version}
AGENTWORKS_DATA_DIR=${DATA_DIR}
AGENTWORKS_SESSION_SECRET=${session_secret}
AGENTWORKS_ADMIN_PASSWORD=${admin_password}
POSTGRES_USER=agentworks
POSTGRES_PASSWORD=${db_password}
POSTGRES_DB=agentworks
AGENTOS_HOST=0.0.0.0
AGENTOS_PORT=7710
AGENTOS_LOG_LEVEL=info
AGENTOS_AWCP_VERSION=awcp/v0.1
EOF

  chmod 600 "${env_file}"
  log_info "Written: ${env_file}"

  # Persist plain-text secrets for the installer's own use (post-start)
  # in a separate file so .env stays secret-ish for docker compose.
  mkdir -p "${CONFIG_DIR}"
  cat > "${CONFIG_DIR}/secrets.json" <<EOF
{
  "admin_password": "${admin_password}",
  "session_secret": "${session_secret}",
  "db_password": "${db_password}"
}
EOF
  chmod 600 "${CONFIG_DIR}/secrets.json"
}

# ---------------------------------------------------------------------------
# 3. Download docker-compose.yml (only when not a local checkout)
# ---------------------------------------------------------------------------
fetch_compose() {
  if is_local_checkout; then
    log_info "Using local docker-compose.yml"
    return 0
  fi

  log_step "Downloading docker-compose.yml ..."
  local dest="${AGENTWORKS_DIR}/docker-compose.yml"
  mkdir -p "$(dirname "${dest}")"

  if ! curl -fsSL -L "${RAW_BASE}/docker-compose.yml" -o "${dest}"; then
    log_error "Failed to download docker-compose.yml"
    exit 1
  fi
  log_info "Downloaded to ${dest}"
}

# ---------------------------------------------------------------------------
# 4. Copy / seed rule-packs
# ---------------------------------------------------------------------------
seed_rule_packs() {
  log_step "Seeding rule-packs ..."

  if is_local_checkout && [[ -d "$(pwd)/rule-packs" ]]; then
    mkdir -p "${RULE_PACKS_DIR}"
    cp -r "$(pwd)/rule-packs/"* "${RULE_PACKS_DIR}/"
    log_info "Copied rule-packs from local checkout"
    return 0
  fi

  # GitHub download for remote installs
  mkdir -p "${RULE_PACKS_DIR}"
  local packs=("smb-starter" "fair-housing" "tcpa-real-estate" "real-estate-tcpa-fair-housing" "hipaa-placeholder")
  for pack in "${packs[@]}"; do
    local src_yaml="${RAW_BASE}/rule-packs/${pack}/${pack}-v0.1.yaml"
    local dest_yaml="${RULE_PACKS_DIR}/${pack}-v0.1.yaml"
    if curl -fsSL -L "${src_yaml}" -o "${dest_yaml}" 2>/dev/null; then
      log_info "Downloaded ${pack} rule-pack"
    else
      log_warn "Could not download ${pack} — skipping"
    fi
  done
}

# ---------------------------------------------------------------------------
# 5. docker compose up -d
# ---------------------------------------------------------------------------
start_services() {
  log_step "Starting services with docker compose ..."

  local compose_dir="${AGENTWORKS_DIR}"
  if is_local_checkout; then
    compose_dir="$(pwd)"
  fi

  cd "${compose_dir}"

  # Ensure data directory exists so the volume mount is clean
  mkdir -p "${DATA_DIR}"

  if ! docker compose up -d 2>&1; then
    log_error "docker compose up -d failed."
    log_error "Run 'docker compose logs' to diagnose."
    exit 1
  fi
  log_info "Services started"
}

# ---------------------------------------------------------------------------
# 6. Poll health endpoint (max 60s, 5s intervals)
# ---------------------------------------------------------------------------
wait_for_health() {
  log_step "Waiting for agentos-d to be ready (max 60s) ..."

  local max_wait=60
  local waited=0
  local interval=5

  while [[ $waited -lt $max_wait ]]; do
    if curl -sf http://localhost:7710/api/health > /dev/null 2>&1; then
      log_info "agentos-d is ready"
      return 0
    fi
    echo -n "."
    sleep $interval
    waited=$((waited + interval))
  done
  echo ""
  log_error "agentos-d did not respond within ${max_wait}s."
  log_error "Run 'docker compose logs agentos-d' for details."
  exit 1
}

# ---------------------------------------------------------------------------
# 7. Create default tenant via POST /api/tenants
# ---------------------------------------------------------------------------
create_tenant() {
  log_step "Creating default tenant ..."

  local payload
  payload=$(cat <<'EOF'
{
  "name": "Default Tenant",
  "description": "Initial tenant created by the AgentWorks OS installer"
}
EOF
)

  local response
  response=$(curl -sf -X POST http://localhost:7710/api/tenants \
    -H "Content-Type: application/json" \
    -d "${payload}" 2>&1) || {
    log_error "Failed to create tenant: ${response}"
    return 1
  }

  local tenant_id
  tenant_id=$(echo "${response}" | python3 -c "import sys,json; print(json.load(sys.stdin)['id'])" 2>/dev/null) || {
    log_error "Could not parse tenant ID from response: ${response}"
    return 1
  }

  log_info "Tenant created: ${tenant_id}"
  echo "${tenant_id}"
}

# ---------------------------------------------------------------------------
# 8. Print success + next steps
# ---------------------------------------------------------------------------
print_success() {
  local tenant_id="${1:-}"
  local admin_password
  admin_password=$(python3 -c "import json; print(json.load(open('${CONFIG_DIR}/secrets.json'))['admin_password'])" 2>/dev/null || echo "see ${CONFIG_DIR}/secrets.json")

  echo ""
  echo "=============================================================================="
  echo -e "${GREEN}AgentWorks OS installed successfully!${NC}"
  echo "=============================================================================="
  echo ""
  echo "  Admin UI:      http://localhost:3000"
  echo "  API:           http://localhost:7710"
  echo "  n8n:           http://localhost:5678"
  echo ""
  echo "  Admin password: ${admin_password}"
  echo "  (also in ${CONFIG_DIR}/secrets.json)"
  echo ""
  if [[ -n "${tenant_id}" ]]; then
    echo "  Tenant ID:     ${tenant_id}"
  fi
  echo ""
  echo "Next steps:"
  echo "  1. Open http://localhost:3000 in your browser"
  echo "  2. Log in with the admin password above"
  echo "  3. Complete the onboarding wizard"
  echo "  4. Run: agentworks mcp configure  (to connect Claude Desktop)"
  echo ""
  echo "Commands:"
  echo "  cd ${AGENTWORKS_DIR} && docker compose ps     # Service status"
  echo "  cd ${AGENTWORKS_DIR} && docker compose logs   # View logs"
  echo "  cd ${AGENTWORKS_DIR} && docker compose down    # Stop services"
  echo ""
  echo "=============================================================================="
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
main() {
  echo ""
  echo "AgentWorks OS Installer v${INSTALLER_VERSION}"
  echo "============================================="
  echo ""

  local unattended=false
  [[ "${1:-}" == "--unattended" ]] && unattended=true

  if [[ "${unattended}" != "true" ]]; then
    echo "This will install AgentWorks OS on this machine."
    echo "Docker is required. Services: agentos-d, scanner-worker, n8n"
    echo ""
    echo -n "Press Enter to continue, or Ctrl+C to cancel: "
    read -r
  fi

  check_docker
  create_env
  fetch_compose
  seed_rule_packs
  start_services
  wait_for_health

  local tenant_id
  tenant_id=$(create_tenant) || true

  print_success "${tenant_id:-}"
}

main "$@"
